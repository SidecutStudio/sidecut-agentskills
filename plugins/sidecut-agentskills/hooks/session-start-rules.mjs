// Personal rules for both hosts. Claude Code reads ~/.claude/rules/*.md; Codex reads one file,
// ~/.codex/AGENTS.md. At the start of a session this rebuilds that file from the rules folder, so
// the two never drift. It only touches a file that already starts with GENERATED: run it once with
// --init to opt in. It reads two local folders, writes one file, prints nothing and never fails.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const GENERATED =
  '<!-- Generated by sidecut-agentskills from ~/.claude/rules/*.md at the start of each session. Edit those files, not this one. -->';

/** The Codex file built from the rule files in `rulesDir`, or null when there are none. */
export function build(rulesDir) {
  if (!existsSync(rulesDir)) return null;
  const parts = readdirSync(rulesDir)
    .filter((name) => name.endsWith('.md'))
    .sort()
    .map((name) =>
      readFileSync(join(rulesDir, name), 'utf8')
        .replace(/^---\n[\s\S]*?\n---\n/, '')
        .trim(),
    )
    .filter(Boolean);
  return parts.length === 0 ? null : `${GENERATED}\n\n${parts.join('\n\n')}\n`;
}

/** Rebuilds the Codex file under `home` when it opted in, or always with `init`. */
export function run(home, init = false) {
  const target = join(home, '.codex', 'AGENTS.md');
  const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
  if (!init && !current?.startsWith(GENERATED)) return 'skipped';
  const next = build(join(home, '.claude', 'rules'));
  if (next === null) return 'no rules';
  if (next === current) return 'current';
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, next);
  return 'written';
}

// Run directly (the hook, or --init by hand), not when a test imports it. Plugin paths can hold spaces.
if (fileURLToPath(import.meta.url) === resolve(process.argv[1] ?? '')) {
  try {
    const result = run(process.env.HOME || homedir(), process.argv.includes('--init'));
    if (process.argv.includes('--init')) console.log(result);
  } catch {
    // A hook never stops a session.
  }
  process.exit(0);
}
