// Personal rules for both hosts. Claude Code reads ~/.claude/rules/*.md; Codex reads one file,
// ~/.codex/AGENTS.md. At the start of a session this rebuilds that file from the rules folder, so
// the two never drift. It only touches a file that already starts with GENERATED: run it once with
// --init to opt in, which first moves an existing file aside. It reads two local places, writes one
// file, prints nothing as a hook and never stops a session.
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  realpathSync,
  renameSync,
  writeFileSync,
} from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const GENERATED =
  '<!-- Generated by sidecut-agentskills from ~/.claude/rules/*.md at the start of each session. Edit those files, not this one. -->';
const BACKUP = 'AGENTS.md.before-sidecut-rules';
const FRONTMATTER = /^---\r?\n([\s\S]*?)\r?\n---\r?\n/;

/** A rule file's text for Codex. A path-scoped rule says which files it is for, as it does in Claude Code. */
function ruleText(text) {
  const front = FRONTMATTER.exec(text);
  const body = text.replace(FRONTMATTER, '').trim();
  const paths = front?.[1]?.match(/^paths:\s*(.+)$/m)?.[1]?.trim();
  return paths ? `When working on files matching ${paths}:\n\n${body}` : body;
}

/** The Codex file built from the rule files in `rulesDir`, or null when there are none. */
export function build(rulesDir) {
  if (!existsSync(rulesDir)) return null;
  const parts = readdirSync(rulesDir, { withFileTypes: true })
    .filter((entry) => entry.name.endsWith('.md') && (entry.isFile() || entry.isSymbolicLink()))
    .map((entry) => entry.name)
    .sort()
    .flatMap((name) => {
      try {
        return [ruleText(readFileSync(join(rulesDir, name), 'utf8'))];
      } catch {
        return []; // A dangling link or unreadable file is skipped, not fatal.
      }
    })
    .filter(Boolean);
  return parts.length === 0 ? null : `${GENERATED}\n\n${parts.join('\n\n')}\n`;
}

/** Writes `text` to `path` through a temporary file, so a reader never sees it half written. */
function writeWhole(path, text) {
  const target = existsSync(path) ? realpathSync(path) : path;
  mkdirSync(dirname(target), { recursive: true });
  const temp = `${target}.${process.pid}.tmp`;
  writeFileSync(temp, text);
  renameSync(temp, target);
}

/** Rebuilds the Codex file under `home` when it opted in, or with `init`, after moving the old one aside. */
export function run(home, init = false) {
  const target = join(home, '.codex', 'AGENTS.md');
  const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
  const optedIn = current?.startsWith(GENERATED) ?? false;
  if (!init && !optedIn) return 'skipped';
  const next = build(join(home, '.claude', 'rules'));
  if (next === null) return 'no rules';
  if (next === current) return 'current';
  if (init && current !== null && !optedIn) {
    const backup = join(home, '.codex', BACKUP);
    if (existsSync(backup))
      throw new Error(`${backup} already exists; move it before running --init again.`);
    writeWhole(backup, current);
  }
  writeWhole(target, next);
  return init && current !== null && !optedIn
    ? `written; the old file is now ${BACKUP}`
    : 'written';
}

// Run directly (the hook, or --init by hand), not when a test imports it. Plugin paths can hold
// spaces or pass through a symlinked cache, so compare real paths.
const self = fileURLToPath(import.meta.url);
const invoked = process.argv[1]
  ? existsSync(process.argv[1])
    ? realpathSync(process.argv[1])
    : ''
  : '';
if (invoked === realpathSync(self)) {
  const init = process.argv.includes('--init');
  const home = process.env.HOME || homedir();
  try {
    const result = run(home, init);
    if (init) console.log(result);
  } catch (error) {
    // A hook never stops a session; --init is run by hand, so it says what went wrong.
    if (init) {
      console.error(`session-start-rules: ${error.message}`);
      process.exit(1);
    }
  }
  process.exit(0);
}
